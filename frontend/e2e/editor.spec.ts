import {test,expect} from './fixtures'
import {execFileSync} from 'node:child_process'
import {fileURLToPath} from 'node:url'
import {readFile} from 'node:fs/promises'
const root=fileURLToPath(new URL('../..',import.meta.url))
const python=process.env.PLAYWRIGHT_PYTHON||(process.platform==='win32'?`${root}/.venv/Scripts/python.exe`:'python')
async function ready(page:import('@playwright/test').Page){
 await page.goto('/')
 const buffer=execFileSync(python,['-c',"from PIL import Image;import io,sys;b=io.BytesIO();Image.new('RGB',(480,360),'#b37842').save(b,'PNG');sys.stdout.buffer.write(b.getvalue())"])
 await page.getByLabel('상품 사진',{exact:true}).setInputFiles({name:'editor.png',mimeType:'image/png',buffer})
 await page.getByLabel('가게명',{exact:true}).fill('편집 테스트 가게')
 await page.getByLabel('상품명',{exact:true}).fill('에스프레소')
 await page.getByLabel('가격',{exact:true}).fill(' 3,000 원 ')
 await page.getByLabel('광고 분위기').selectOption('warm')
 await page.getByRole('button',{name:'상품 정보와 사진 저장'}).click()
 await page.getByRole('button',{name:'4전략 카피 생성'}).click()
 await expect(page.getByText('카피 상태: completed')).toBeVisible()
 await page.getByRole('button',{name:'광고 4장 렌더링'}).click()
 await expect(page.getByText('렌더링 상태: completed')).toBeVisible({timeout:45000})
}
test('actual edit twice, reload current copy, stale mock ranking, exact PNG and one-page A4 download',async({page},info)=>{
 test.setTimeout(120000);await ready(page)
 const editor=page.getByRole('region',{name:'광고 편집 및 다운로드'})
 const ranks=page.getByRole('region',{name:'광고 임시 순위'})
 await ranks.getByRole('button',{name:'임시 순위 확인'}).click()
 await expect(ranks.getByRole('listitem')).toHaveCount(4)
 await editor.getByRole('button',{name:'문구 편집',exact:true}).click()
 await expect(editor.getByRole('button',{name:'적용하고 재렌더링'})).toBeDisabled()
 await editor.getByLabel('제목',{exact:true}).fill('한 잔에 담은 여유')
 await editor.getByRole('button',{name:'적용하고 재렌더링'}).click()
 await expect(editor.getByRole('heading')).toContainText('revision 2',{timeout:45000})
 await expect(ranks.getByRole('listitem')).toHaveCount(0)
 await editor.getByRole('button',{name:'문구 편집',exact:true}).click()
 await expect(editor.getByLabel('제목',{exact:true})).toHaveValue('한 잔에 담은 여유')
 await editor.getByLabel('제목',{exact:true}).fill('다시 만나는 한 잔')
 await editor.getByRole('button',{name:'적용하고 재렌더링'}).click()
 await expect(editor.getByRole('heading')).toContainText('revision 3',{timeout:45000})
 await page.getByRole('button',{name:'광고 4장 렌더링'}).click()
 await expect(editor.getByRole('heading')).toContainText('revision 3')
 await expect(editor.getByText('현재 성공본: 다시 만나는 한 잔')).toBeVisible()
 for(const format of ['png','pdf'] as const){
  const event=page.waitForEvent('download');await editor.getByRole('button',{name:format==='png'?'PNG 다운로드':'A4 PDF 다운로드',exact:true}).click()
  const file=await event;expect(file.suggestedFilename()).toMatch(new RegExp(`r3\\.${format}$`))
  await file.saveAs(info.outputPath(`edited.${format}`));const data=await readFile(info.outputPath(`edited.${format}`))
  if(format==='png'){expect(data.readUInt32BE(16)).toBe(1080);expect(data.readUInt32BE(20)).toBe(1350)}
  else{expect(data.subarray(0,5).toString()).toBe('%PDF-');expect(data.toString('latin1').match(/\/Type\s*\/Page\b/g)).toHaveLength(1)}
 }
 await page.reload();await page.getByRole('button',{name:'저장 정보 다시 조회'}).click()
 await expect(editor.getByText('현재 성공본: 다시 만나는 한 잔')).toBeVisible()
 await editor.getByRole('button',{name:'문구 편집',exact:true}).click()
 await expect(editor.getByLabel('제목',{exact:true})).toHaveValue('다시 만나는 한 잔')
 await editor.getByLabel('제목',{exact:true}).fill('저장하지 않을 문구')
 await editor.getByRole('button',{name:'편집 취소'}).click()
 await expect(editor.getByRole('button',{name:'문구 편집',exact:true})).toBeFocused()
 await page.getByRole('button',{name:'감성 광고 확대 보기'}).click()
 await expect(page.getByRole('dialog')).toBeVisible();await page.keyboard.press('Escape')
 await page.screenshot({path:info.outputPath('editor-desktop.png'),fullPage:true})
 await page.setViewportSize({width:375,height:900})
 await expect(page.locator('body')).toHaveJSProperty('scrollWidth',375)
 await page.screenshot({path:info.outputPath('editor-mobile.png'),fullPage:true})
})
test('simulated edit failure preserves last PNG and expired download is explained',async({page})=>{
 test.setTimeout(90000);await ready(page)
 const editor=page.getByRole('region',{name:'광고 편집 및 다운로드'})
 await page.route('**/candidates/*',async route=>{
  if(route.request().method()==='PATCH')await route.fulfill({status:409,contentType:'application/json',body:JSON.stringify({error:{message:'다른 편집이 적용됐습니다. 다시 조회해 주세요.'}})})
  else await route.continue()
 })
 await editor.getByRole('button',{name:'문구 편집',exact:true}).click()
 await editor.getByLabel('제목',{exact:true}).fill('수정 문구')
 await editor.getByRole('button',{name:'적용하고 재렌더링'}).click()
 await expect(editor.getByRole('alert')).toContainText('다른 편집')
 await expect(page.getByRole('region',{name:'4전략 광고 이미지'}).getByRole('img')).toHaveCount(4)
 await editor.getByRole('button',{name:'편집 취소'}).click()
 await page.route('**/download?**',r=>r.fulfill({status:410,contentType:'application/json',body:JSON.stringify({error:{message:'광고가 만료됐습니다.'}})}))
 await editor.getByRole('button',{name:'PNG 다운로드',exact:true}).click()
 await expect(editor.getByRole('alert')).toContainText('만료')
})
