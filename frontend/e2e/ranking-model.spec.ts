import {test,expect} from './fixtures'
import {execFileSync} from 'node:child_process'
import {fileURLToPath} from 'node:url'
import {writeFile} from 'node:fs/promises'
const root=fileURLToPath(new URL('../..',import.meta.url))
const python=process.env.PLAYWRIGHT_PYTHON||(process.platform==='win32'?`${root}/.venv/Scripts/python.exe`:'python')

test('actual B model: final PNG scores, diagnostics separation, edit invalidation and downloads',async({page},info)=>{
 test.skip(process.env.PLAYWRIGHT_REQUIRE_RANKING_MODEL!=='1','Explicit local B bundle; no model download in CI')
 test.setTimeout(180000)
 const errors:string[]=[];page.on('console',e=>{if(e.type()==='error')errors.push(e.text())})
 await page.goto('/')
 if(process.env.PLAYWRIGHT_RANKING_SAMPLE)await page.getByLabel('상품 사진',{exact:true}).setInputFiles(process.env.PLAYWRIGHT_RANKING_SAMPLE)
 else{
  const buffer=execFileSync(python,['-c',"from PIL import Image;import io,sys;b=io.BytesIO();Image.new('RGB',(480,360),'#b37842').save(b,'PNG');sys.stdout.buffer.write(b.getvalue())"])
  await page.getByLabel('상품 사진',{exact:true}).setInputFiles({name:'rank-product.png',mimeType:'image/png',buffer})
 }
 await page.getByLabel('가게명',{exact:true}).fill('모델 연동 테스트')
 await page.getByLabel('상품명',{exact:true}).fill('에스프레소')
 await page.getByLabel('가격',{exact:true}).fill(' 3,000 원 ')
 await page.getByLabel('광고 분위기').selectOption('warm')
 await page.getByRole('button',{name:'상품 정보와 사진 저장'}).click()
 await page.getByRole('button',{name:'4전략 카피 생성'}).click()
 await expect(page.getByText('카피 상태: completed')).toBeVisible()
 const rendered=page.waitForResponse(async r=>r.url().endsWith('/rendering')&&r.request().method()==='GET'&&r.status()===200&&(await r.json()).status==='completed')
 await page.getByRole('button',{name:'광고 4장 렌더링'}).click()
 await expect(page.getByText('렌더링 상태: completed')).toBeVisible({timeout:45000})
 const renderBody=await(await rendered).json()
 const ranks=page.getByRole('region',{name:'광고 선호 순위'})
 const api=page.waitForResponse(async r=>r.url().endsWith('/ranking')&&r.request().method()==='GET'&&r.status()===200&&(await r.json()).status==='completed')
 await ranks.getByRole('button',{name:'순위 계산'}).click()
 const rankBody=await(await api).json()
 await expect(ranks.getByText(/실제 모델 실행 완료/)).toBeVisible({timeout:60000})
 await expect(ranks.getByText('실행 모드: 실제 모델 · 자동 Mock 전환 없음')).toBeVisible()
 await expect(ranks.getByText(/모델 버전: bt-logistic-v1/)).toBeVisible()
 await expect(ranks.getByRole('listitem')).toHaveCount(4)
 expect(rankBody.ranking.source).toBe('model')
 expect(rankBody.revision).toBe(renderBody.revision)
 const ids=renderBody.candidates.map((c:{candidate_id:string})=>c.candidate_id)
 expect(rankBody.ranking.items.map((i:{candidate_id:string})=>i.candidate_id).sort()).toEqual(ids.sort())
 for(const item of rankBody.ranking.items){
  const candidate=renderBody.candidates.find((c:{candidate_id:string})=>c.candidate_id===item.candidate_id)
  await expect(ranks.getByRole('listitem').nth(item.rank-1)).toContainText(candidate.strategy)
  await expect(ranks.getByRole('listitem').nth(item.rank-1)).toContainText(`score: ${item.score}`)
 }
 await writeFile(info.outputPath('ranking-model-result.json'),JSON.stringify({render:renderBody,ranking:rankBody},null,2))
 expect(await ranks.getByRole('list').innerText()).not.toMatch(/%|CTR/)
 await expect(ranks.getByText('시연용 임시 순위이며 실제 광고 품질 평가 결과가 아닙니다')).toHaveCount(0)
 const diagnostics=page.getByRole('region',{name:'규칙 기반 가독성 진단'})
 await diagnostics.getByRole('button',{name:'가독성 진단 실행'}).click()
 await expect(diagnostics.getByRole('article')).toHaveCount(4)
 await expect(diagnostics.getByText(/score:/)).toHaveCount(0)
 await page.screenshot({path:info.outputPath('ranking-model-desktop.png'),fullPage:true})
 const editor=page.getByRole('region',{name:'광고 편집 및 다운로드'})
 await editor.getByRole('button',{name:'문구 편집',exact:true}).click()
 await editor.getByLabel('제목',{exact:true}).fill('다시 만나는 한 잔')
 await editor.getByRole('button',{name:'적용하고 재렌더링'}).click()
 await expect(editor.getByRole('heading')).toContainText('revision 2',{timeout:45000})
 await expect(ranks.getByRole('listitem')).toHaveCount(0)
 await ranks.getByRole('button',{name:'순위 계산'}).click()
 await expect(ranks.getByText(/실제 모델 실행 완료/)).toBeVisible({timeout:60000})
 for(const name of ['PNG 다운로드','A4 PDF 다운로드']){
  const download=page.waitForEvent('download');await editor.getByRole('button',{name,exact:true}).click()
  await(await download).saveAs(info.outputPath(name.startsWith('PNG')?'model-edited.png':'model-edited.pdf'))
 }
 await expect(page.getByLabel('가격',{exact:true})).toHaveValue(' 3,000 원 ')
 await page.setViewportSize({width:375,height:900})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.screenshot({path:info.outputPath('ranking-model-mobile.png'),fullPage:true})
 expect(errors).toEqual([])
})
