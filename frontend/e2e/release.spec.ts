import {test,expect} from './fixtures'
import {execFileSync} from 'node:child_process'
import {fileURLToPath} from 'node:url'
import {writeFile} from 'node:fs/promises'
const root=fileURLToPath(new URL('../..',import.meta.url))
const python=process.env.PLAYWRIGHT_PYTHON||(process.platform==='win32'?`${root}/.venv/Scripts/python.exe`:'python')
const real=process.env.PLAYWRIGHT_RELEASE_MODELS==='1'
test.use({httpCredentials:{username:process.env.HANJANG_PRESENTATION_USER||'presenter',password:process.env.HANJANG_PRESENTATION_PASSWORD||'synthetic-ci-presentation-password'}})

test('built presentation: complete flow with explicit model provenance',async({page,request},info)=>{
 test.skip(process.env.PLAYWRIGHT_RELEASE!=='1','Opt-in authenticated built frontend, never launches a tunnel')
 test.setTimeout(300000)
 const errors:string[]=[];page.on('console',e=>{if(e.type()==='error')errors.push(e.text())})
 const ready=await request.get('/ready');expect(ready.status()).toBe(200)
 expect((await ready.json()).check_level).toBe('configuration_not_inference')
 await page.goto('/')
 const sample=process.env.PLAYWRIGHT_RELEASE_SAMPLE
 if(sample)await page.getByLabel('상품 사진',{exact:true}).setInputFiles(sample)
 else{
  const buffer=execFileSync(python,['-c',"from PIL import Image,ImageDraw;import io,sys;i=Image.new('RGB',(640,480),'#466b8a');d=ImageDraw.Draw(i);d.rounded_rectangle((220,90,420,390),radius=30,fill='#eeeeee');d.rectangle((240,190,400,290),fill='#e87720');b=io.BytesIO();i.save(b,'PNG');sys.stdout.buffer.write(b.getvalue())"])
  await page.getByLabel('상품 사진',{exact:true}).setInputFiles({name:'synthetic-demo-product.png',mimeType:'image/png',buffer})
 }
 await page.getByLabel('가게명',{exact:true}).fill('발표용 테스트 가게')
 await page.getByLabel('상품명',{exact:true}).fill('에스프레소')
 await page.getByLabel('가격',{exact:true}).fill(' 3,000 원 ')
 await page.getByLabel('광고 분위기').selectOption('warm')
 await page.getByRole('button',{name:'상품 정보와 사진 저장'}).click()
 await page.getByRole('button',{name:'배경 제거 시작'}).click()
 const photos=page.getByRole('region',{name:'사진 전처리'})
 await expect(photos.getByText(/사진 처리 상태: (completed|failed)/)).toBeVisible({timeout:125000})
 if(real){
  await expect(photos.getByAltText('배경 제거 처리본 사진')).toBeVisible()
  await photos.getByRole('button',{name:'처리본 사용'}).click()
  await expect(photos.getByRole('button',{name:'처리본 사용'})).toHaveAttribute('aria-pressed','true')
  await photos.getByRole('button',{name:'원본 사용'}).click()
 }else await expect(photos.getByText(/배경 제거 모델이 없습니다/)).toBeVisible()
 await page.getByRole('button',{name:'선택 사진 분석'}).click()
 const analysis=page.getByRole('region',{name:'상품 사진 분석'})
 await expect(analysis.getByText('분석 상태: completed')).toBeVisible({timeout:130000})
 await expect(analysis.getByText(/#[0-9A-F]{6}/).first()).toBeVisible()
 await expect(analysis.getByText(real?'CLIP: 실제 모델 시각 단서':'CLIP: 사용 불가 · 추정 단서 없음')).toBeVisible()
 await page.getByRole('button',{name:'4전략 카피 생성'}).click()
 await expect(page.getByText('카피 상태: completed')).toBeVisible()
 const rendering=page.waitForResponse(async r=>r.url().endsWith('/rendering')&&r.request().method()==='GET'&&r.status()===200&&(await r.json()).status==='completed')
 await page.getByRole('button',{name:'광고 4장 렌더링'}).click()
 await expect(page.getByText('렌더링 상태: completed')).toBeVisible({timeout:45000})
 const rendered=await(await rendering).json();expect(rendered.candidates).toHaveLength(4)
 const ranks=page.getByRole('region',{name:'광고 선호 순위'})
 const response=page.waitForResponse(async r=>r.url().endsWith('/ranking')&&r.request().method()==='GET'&&r.status()===200&&(await r.json()).status==='completed')
 await ranks.getByRole('button',{name:'순위 계산'}).click()
 await expect(ranks.getByRole('listitem')).toHaveCount(4,{timeout:60000})
 const ranked=await(await response).json()
 expect(ranked.ranking.source).toBe(real?'model':'mock')
 expect(ranked.revision).toBe(rendered.revision)
 expect(ranked.ranking.items.map((i:{candidate_id:string})=>i.candidate_id).sort()).toEqual(rendered.candidates.map((c:{candidate_id:string})=>c.candidate_id).sort())
 expect(ranked.ranking.items.map((i:{rank:number})=>i.rank)).toEqual([1,2,3,4])
 if(real){
  await expect(ranks.getByText(/모델 버전: bt-logistic-v1/)).toBeVisible()
  const scores=ranked.ranking.items.map((i:{score:number})=>i.score)
  expect(scores).toEqual([...scores].sort((a,b)=>b-a))
 }else await expect(ranks.getByText('시연용 임시 순위이며 실제 광고 품질 평가 결과가 아닙니다')).toBeVisible()
 const diagnostics=page.getByRole('region',{name:'규칙 기반 가독성 진단'})
 await diagnostics.getByRole('button',{name:'가독성 진단 실행'}).click()
 await expect(diagnostics.getByRole('article')).toHaveCount(4)
 await expect(diagnostics.getByText(/score:/)).toHaveCount(0)
 await page.screenshot({path:info.outputPath('release-desktop.png'),fullPage:true})
 const editor=page.getByRole('region',{name:'광고 편집 및 다운로드'})
 await editor.getByRole('button',{name:'문구 편집',exact:true}).click()
 await editor.getByLabel('제목',{exact:true}).fill('다시 만나는 한 잔')
 await editor.getByRole('button',{name:'적용하고 재렌더링'}).click()
 await expect(editor.getByRole('heading')).toContainText('revision 2',{timeout:45000})
 await expect(ranks.getByRole('listitem')).toHaveCount(0)
 await ranks.getByRole('button',{name:'순위 계산'}).click()
 await expect(ranks.getByRole('listitem')).toHaveCount(4,{timeout:60000})
 for(const name of ['PNG 다운로드','A4 PDF 다운로드']){
  const download=page.waitForEvent('download');await editor.getByRole('button',{name,exact:true}).click()
  await(await download).saveAs(info.outputPath(name.startsWith('PNG')?'release-edited.png':'release-edited.pdf'))
 }
 await expect(page.getByLabel('가격',{exact:true})).toHaveValue(' 3,000 원 ')
 await page.reload();await page.getByRole('button',{name:'저장 정보 다시 조회'}).click()
 await expect(page.getByLabel('상품명',{exact:true})).toHaveValue('에스프레소')
 await page.setViewportSize({width:375,height:900})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.screenshot({path:info.outputPath('release-mobile.png'),fullPage:true})
 await writeFile(info.outputPath('release-result.json'),JSON.stringify({realModels:real,copy:'mock',rendering:rendered,ranking:ranked},null,2))
 expect(errors).toEqual([])
})
