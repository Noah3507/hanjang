import { test, expect } from './fixtures'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
const root = fileURLToPath(new URL('../..', import.meta.url))
const python = process.env.PLAYWRIGHT_PYTHON || (process.platform === 'win32' ? `${root}/.venv/Scripts/python.exe` : 'python')
async function save(page: import('@playwright/test').Page) {
  await page.goto('/')
  const buffer = execFileSync(python, ['-c', "from PIL import Image,ImageDraw;import io,sys;i=Image.new('RGB',(400,300),'#faf3de');d=ImageDraw.Draw(i);d.ellipse((20,20,380,280),fill='orange',outline='green',width=10);b=io.BytesIO();i.save(b,'PNG');sys.stdout.buffer.write(b.getvalue())"])
  await page.getByLabel('상품 사진', { exact: true }).setInputFiles({ name: 'synthetic.png', mimeType: 'image/png', buffer })
  await page.getByLabel('가게명', { exact: true }).fill('쿠지라스토랑')
  await page.getByLabel('상품명', { exact: true }).fill('아부라소바')
  await page.getByLabel('가격', { exact: true }).fill(' 10,500 원 ')
  await page.getByLabel('광고 분위기').selectOption('warm')
  await page.getByLabel('주소 (선택)').fill('서울 테스트 거리 123')
  await page.getByLabel('Instagram (선택)').fill('@fixture_shop')
  await page.getByLabel('상품 특징·강조 포인트 (선택)').fill('특제 소스, 쫄깃한 면발')
  await page.getByRole('button', { name: '상품 정보와 사진 저장' }).click()
  await page.getByRole('button', { name: '4전략 카피 생성' }).click()
  await expect(page.getByText('카피 상태: completed')).toBeVisible()
}
test('actual API + Mock copy + real Chromium PNGs: render, reload, stale, re-render and mobile', async ({ page }, info) => {
  test.setTimeout(90_000)
  const errors: string[] = []
  page.on('console', e => { if (e.type() === 'error') errors.push(e.text()) })
  await save(page)
  const panel = page.getByRole('region', { name: '4전략 광고 이미지' })
  await panel.getByRole('button', { name: '광고 4장 렌더링' }).click()
  await expect(panel.getByText('렌더링 상태: completed')).toBeVisible({ timeout: 30_000 })
  await expect(panel.getByRole('img')).toHaveCount(4)
  for (const image of await panel.getByRole('img').all()) {
    await expect(image).toBeVisible()
    await expect.poll(() => image.evaluate((i: HTMLImageElement) => i.naturalWidth)).toBe(1080)
    expect(await image.evaluate((i: HTMLImageElement) => i.naturalHeight)).toBe(1350)
  }
  await expect(panel.getByText(/Mock 카피 사용/)).toBeVisible()
  await page.screenshot({ path: info.outputPath('render-four.png'), fullPage: true })
  await page.reload(); await page.getByRole('button', { name: '저장 정보 다시 조회' }).click()
  await expect(panel.getByRole('img')).toHaveCount(4)
  await page.getByLabel('상품 특징·강조 포인트 (선택)').fill('새 사용자 특징')
  await page.getByRole('button', { name: '상품 정보와 사진 저장' }).click()
  await expect(panel.getByRole('alert')).toContainText('최신 결과가 아닙니다')
  await expect(panel.getByRole('button', { name: '광고 4장 렌더링' })).toBeDisabled()
  await page.getByRole('button', { name: '4전략 카피 생성' }).click()
  await expect(panel.getByRole('button', { name: '광고 4장 렌더링' })).toBeEnabled()
  await panel.getByRole('button', { name: '광고 4장 렌더링' }).click()
  await expect(panel.getByRole('alert')).toHaveCount(0)
  await expect(panel.getByText('렌더링 상태: completed')).toBeVisible({ timeout: 30_000 })
  await expect(page.getByLabel('가격', { exact: true })).toHaveValue(' 10,500 원 ')
  await page.setViewportSize({ width: 375, height: 812 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('render-mobile.png'), fullPage: true })
  expect(errors).toEqual([])
})
test('simulated render failure keeps saved input and retry available', async ({ page }) => {
  await save(page)
  await page.route('**/rendering', route => route.fulfill({ status: 503, json: { error: { message: '렌더링 worker를 사용할 수 없습니다.' } } }))
  const panel = page.getByRole('region', { name: '4전략 광고 이미지' })
  await panel.getByRole('button', { name: '광고 4장 렌더링' }).click()
  await expect(panel.getByRole('alert')).toContainText('worker')
  await expect(page.getByLabel('가격', { exact: true })).toHaveValue(' 10,500 원 ')
})
